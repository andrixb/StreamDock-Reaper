// Regenerates "ReaperControl Auto-Setup.lua" so it embeds the current
// ReaperControl.ReaperOSC verbatim. Run: node reaper/build-setup-script.js
const fs = require('fs');
const path = require('path');

const pattern = fs.readFileSync(path.join(__dirname, 'ReaperControl.ReaperOSC'), 'utf8');
if (pattern.includes(']==]')) throw new Error('pattern contains the Lua long-bracket terminator');

const lua = `-- ReaperControl Auto-Setup  (generated by build-setup-script.js — do not edit by hand)
--
-- 1. Installs ReaperControl.ReaperOSC into REAPER's OSC folder.
-- 2. Opens Preferences > Control/OSC/web and tells you the exact values to enter.
--
-- The control surface itself must be added in the Preferences dialog: REAPER
-- rewrites reaper.ini on exit, so editing that file from a script is unreliable.

local PATTERN_NAME = "ReaperControl.ReaperOSC"
local PATTERN_CONTENT = [==[
${pattern}]==]

local sep = reaper.GetOS():match("Win") and "\\\\" or "/"
local osc_dir = reaper.GetResourcePath() .. sep .. "OSC"
local dst = osc_dir .. sep .. PATTERN_NAME

reaper.RecursiveCreateDirectory(osc_dir, 0)
local f = io.open(dst, "wb")
local ok = false
if f then
  ok = f:write(PATTERN_CONTENT) ~= nil
  f:close()
end

if not ok then
  reaper.ShowMessageBox("Could not write:\\n" .. dst .. "\\n\\nCheck folder permissions, or copy " ..
    PATTERN_NAME .. " there manually.", "ReaperControl Auto-Setup", 0)
  return
end

local msg = "Installed " .. PATTERN_NAME .. " to:\\n" .. dst .. "\\n\\n" ..
  "Now add the control surface (Preferences opens after you click OK):\\n\\n" ..
  "  1. Control/OSC/web  >  Add  >  OSC (Open Sound Control)\\n" ..
  "     (if an 'OSC: ReaperControl' entry already exists, select it and click Edit)\\n" ..
  "  2. Device name:        ReaperControl\\n" ..
  "  3. Pattern config:     ReaperControl\\n" ..
  "  4. Mode:               Configure device IP + local port\\n" ..
  "  5. Device port:        9000\\n" ..
  "  6. Device IP:          127.0.0.1\\n" ..
  "  7. Local listen port:  8000\\n" ..
  "  8. OK, then OK/Apply in Preferences.\\n\\n" ..
  "No restart is needed. The StreamDock keys stop showing 'NO REAPER' within a few seconds."

reaper.ShowMessageBox(msg, "ReaperControl Auto-Setup", 0)
reaper.ViewPrefs(0, "csurf")
`;

fs.writeFileSync(path.join(__dirname, 'ReaperControl Auto-Setup.lua'), lua);
console.log('Wrote ReaperControl Auto-Setup.lua');
